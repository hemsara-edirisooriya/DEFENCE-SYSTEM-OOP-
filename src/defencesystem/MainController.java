    private void btnCollectInformationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCollectInformationActionPerformed
        // TODO add your handling code here:
        String status = combMaincontroller.getSelectedItem().toString();
        String  count = null;
        String fuel = null;
        String ammoCount = null;
        
        if(status.equals("Tank")){
            count = Integer.toString(tank.getSoldierCount());
            fuel = Integer.toString(tank.getFuelCount());
            ammoCount = Integer.toString(tank.getAmmoCount());
        }else if(status.equals("Helicopter")){
            count = Integer.toString(helicopter.getSoldierCount());
            fuel = Integer.toString(helicopter.getFuelCount());
            ammoCount = Integer.toString(helicopter.getAmmoCount());
        }else if(status.equals("Submarine")){
            count = Integer.toString(subMarine.getSoldierCount());
            fuel = Integer.toString(subMarine.getFuelCount());
            ammoCount = Integer.toString(subMarine.getAmmoCount());
        }else{
            txtALeft.setText("Not selected");
        }
        
        lblSoldierCount.setText(count);
        lblFuelCount.setText(fuel);
        lblAmmoCount.setText(ammoCount);
    }//GEN-LAST:event_btnCollectInformationActionPerformed

