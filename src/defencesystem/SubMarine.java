    private void btnShootActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShootActionPerformed
        // TODO add your handling code here:
        int enargy = sldEnergy.getValue();
        int ammo = (int) spnAmmoCount.getValue();
        
        
        if (ammo > 10) {
            enargy = enargy - 1;
            spnAmmoCount.setValue(ammo - 1);
            sldEnergy.setValue(enargy);
        }else{
            spnAmmoCount.setValue(ammo - 1);
            mainController.worningAmmo("SubMarin");
        }
        
    }//GEN-LAST:event_btnShootActionPerformed

